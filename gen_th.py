def make_srs(sid, title, intro, scope_list, actors_list, features_list, nfr_list, tables_list, interfaces_list, constraints_list, assumptions_list):
    scope = "\n".join("1. " + s for s in scope_list)
    
    actors_desc = "\n".join("**" + a[0] + "**: " + a[1] for a in actors_list)
    actors_table = "\n".join("| " + a[0] + " | " + a[1] + " |" for a in actors_list)
    
    features = ""
    for f in features_list:
        fid, fname, pri, desc, inputs, outputs, bizrule = f
        features += "\n### " + fid + " " + fname + "\n"
        features += "| หัวข้อ | รายละเอียด |\n|--------|-----------|\n"
        features += "| **ลำดับความสำคัญ** | " + pri + " |\n"
        features += "| **คำอธิบาย** | " + desc + " |\n"
        features += "| **ผู้กระทำ** | _________________________ |\n"
        features += "| **ข้อมูลนำเข้า** | " + inputs + " |\n"
        features += "| **กระบวนการทำงาน** | 1. _________________________<br>2. _________________________<br>3. _________________________ |\n"
        features += "| **ข้อมูลส่งออก** | " + outputs + " |\n"
        features += "| **กฎทางธุรกิจ** | " + bizrule + " |\n"
        features += "| **ผลลัพธ์ที่คาดหวัง** | _________________________ |\n"
        features += "| **ผู้ทดสอบ** | _________________________ |\n"
    
    nfr = "\n".join("| **" + n[0] + "** | " + n[1] + " |" for n in nfr_list)
    tables = "\n".join("| " + t[0] + " | " + t[1] + " | " + t[2] + " |" for t in tables_list)
    interfaces = "\n".join("| " + i[0] + " | " + i[1] + " |" for i in interfaces_list)
    constraints = "\n".join("- " + c for c in constraints_list)
    assumptions = "\n".join("- " + a for a in assumptions_list)
    
    return TEMPLATE.format(
        title=title,
        intro=intro,
        scope=scope,
        actors_desc=actors_desc,
        actors_table=actors_table,
        features=features,
        nfr=nfr,
        tables=tables,
        interfaces=interfaces,
        constraints=constraints,
        assumptions=assumptions,
    )

